#!/usr/bin/env python3
"""Tamper evidence for the registered record (task T3).

The record is every file under registrations/ and every registration text,
frozen script, log and results file under experiments/. Its hashes live in
registrations/RECORD_HASHES.tsv (path, sha256, bytes), one row per file,
sorted by path.

    build            append rows for record files not yet listed; refuses to
                     run if any listed file has changed or is missing
    check            fail if any listed file is missing or differs, or if a
                     record file is not listed
    compare --base R fail if any row present in R's copy of the TSV is absent
                     or different now (rows may be added, never changed)

Only git-tracked and untracked-but-not-ignored files are considered, so data
that .gitignore keeps out of the repository is never listed. Standard library
only; run from anywhere inside the repository.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import subprocess
import sys

HASHES_PATH = "registrations/RECORD_HASHES.tsv"
HEADER = "path\tsha256\tbytes"

# What the record is.
RECORD_DIRS = ("registrations", "experiments")
# Generated here, or an index kept by hand rather than a record file.
EXCLUDE_FILES = {
    HASHES_PATH,
    "registrations/record_index.tsv",  # generated by tools/record_index.py
    "experiments/README.md",           # index of the folders, not a record
}
# Reference material, not a registration (see experiments/README.md).
EXCLUDE_PREFIXES = ("experiments/openai-math-lean/",)


def repo_root() -> str:
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                         check=True, capture_output=True, text=True)
    return out.stdout.strip()


def record_files(root: str) -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard",
         "--", *RECORD_DIRS],
        cwd=root, check=True, capture_output=True)
    paths = set()
    for raw in out.stdout.split(b"\0"):
        if not raw:
            continue
        p = raw.decode("utf-8")
        if p in EXCLUDE_FILES or p.startswith(EXCLUDE_PREFIXES):
            continue
        if os.path.isfile(os.path.join(root, p)):  # skip deleted-but-cached
            paths.add(p)
    return sorted(paths)


def digest(path: str) -> tuple[str, int]:
    h = hashlib.sha256()
    n = 0
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
            n += len(chunk)
    return h.hexdigest(), n


def parse_tsv(text: str, source: str) -> dict[str, tuple[str, int]]:
    rows: dict[str, tuple[str, int]] = {}
    lines = text.splitlines()
    if not lines or lines[0] != HEADER:
        sys.exit(f"{source}: first line must be '{HEADER}'")
    for i, line in enumerate(lines[1:], start=2):
        if not line:
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            sys.exit(f"{source}:{i}: expected 3 tab-separated fields")
        path, sha, size = parts
        if len(sha) != 64 or any(c not in "0123456789abcdef" for c in sha):
            sys.exit(f"{source}:{i}: bad sha256")
        if path in rows:
            sys.exit(f"{source}:{i}: duplicate path {path}")
        rows[path] = (sha, int(size))
    return rows


def load_tsv(root: str) -> dict[str, tuple[str, int]]:
    full = os.path.join(root, HASHES_PATH)
    if not os.path.exists(full):
        return {}
    with open(full, encoding="utf-8") as f:
        return parse_tsv(f.read(), HASHES_PATH)


def write_tsv(root: str, rows: dict[str, tuple[str, int]]) -> None:
    lines = [HEADER] + [f"{p}\t{s}\t{n}" for p, (s, n) in sorted(rows.items())]
    with open(os.path.join(root, HASHES_PATH), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def cmd_build(root: str) -> int:
    listed = load_tsv(root)
    present = record_files(root)
    problems = []
    for p, (sha, size) in listed.items():
        full = os.path.join(root, p)
        if not os.path.isfile(full):
            problems.append(f"MISSING  {p}")
            continue
        s, n = digest(full)
        if (s, n) != (sha, size):
            problems.append(f"CHANGED  {p}")
    if problems:
        print("build refused: listed files may not change or disappear", file=sys.stderr)
        print("\n".join(problems), file=sys.stderr)
        return 1
    added = 0
    for p in present:
        if p not in listed:
            listed[p] = digest(os.path.join(root, p))
            print(f"ADDED    {p}")
            added += 1
    write_tsv(root, listed)
    print(f"{HASHES_PATH}: {len(listed)} files listed, {added} added")
    return 0


def cmd_check(root: str) -> int:
    listed = load_tsv(root)
    if not listed:
        print(f"{HASHES_PATH} is missing or empty", file=sys.stderr)
        return 1
    failures = []
    for p, (sha, size) in sorted(listed.items()):
        full = os.path.join(root, p)
        if not os.path.isfile(full):
            failures.append(f"MISSING  {p}")
            continue
        s, n = digest(full)
        if s != sha or n != size:
            failures.append(f"CHANGED  {p}  listed {sha[:12]} {size} B, found {s[:12]} {n} B")
    for p in record_files(root):
        if p not in listed:
            failures.append(f"UNLISTED {p}  (run tools/record_hashes.py build to list it)")
    if failures:
        print("record check FAILED", file=sys.stderr)
        print("\n".join(failures), file=sys.stderr)
        return 1
    print(f"record check passed: {len(listed)} files match {HASHES_PATH}")
    return 0


def cmd_compare(root: str, base: str) -> int:
    out = subprocess.run(["git", "show", f"{base}:{HASHES_PATH}"],
                         cwd=root, capture_output=True, text=True)
    if out.returncode != 0:
        print(f"{HASHES_PATH} does not exist at {base}; nothing to compare")
        return 0
    before = parse_tsv(out.stdout, f"{base}:{HASHES_PATH}")
    now = load_tsv(root)
    failures = []
    for p, (sha, size) in sorted(before.items()):
        if p not in now:
            failures.append(f"REMOVED  {p}")
        elif now[p] != (sha, size):
            failures.append(f"CHANGED  {p}  was {sha[:12]} {size} B, now {now[p][0][:12]} {now[p][1]} B")
    added = sorted(set(now) - set(before))
    for p in added:
        print(f"ADDED    {p}")
    if failures:
        print(f"record compare against {base} FAILED: rows may be added, never changed or removed",
              file=sys.stderr)
        print("\n".join(failures), file=sys.stderr)
        return 1
    print(f"record compare against {base} passed: {len(before)} rows unchanged, {len(added)} added")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    sub.add_parser("check")
    cmp_ = sub.add_parser("compare")
    cmp_.add_argument("--base", required=True, help="git ref holding the earlier TSV")
    args = ap.parse_args()
    root = repo_root()
    if args.cmd == "build":
        return cmd_build(root)
    if args.cmd == "check":
        return cmd_check(root)
    return cmd_compare(root, args.base)


if __name__ == "__main__":
    sys.exit(main())
